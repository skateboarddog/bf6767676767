        {"^Secret Quests: ", "秘密任务："},
        {"^JobID %[", "服务器 ID ["},
        {"^Quantum Premium %[", "Quantum Premium ["},
    }

    local function trim(s)
        return s and (s:gsub("^%s+", ""):gsub("%s+$", "")) or s
    end
    local function tr(raw)
        if type(raw) ~= "string" or raw == "" then return raw end
        if T[raw] then return T[raw] end
        local t2 = T[trim(raw)]
        if t2 then return t2 end
        for i = 1, #Dyn do
            local pre, zh = Dyn[i][1], Dyn[i][2]
            local rest = raw:match(pre .. "(.*)$")
            if rest then return zh .. rest end
        end
        return raw
    end

    -- 不 hook 全局 Instance.new（PC 执行器 hook 该核心函数极易卡死）
    -- 改成：定时扫描 GUI，每个文本对象只连接一次
    local processed = setmetatable({}, { __mode = "k" })

    local function handleObject(obj, class)
        if processed[obj] then return end
        processed[obj] = true

        local function applyText()
            local ok, cur = pcall(function() return obj.Text end)
            if not ok then return end
            local nt = tr(cur)
            if nt ~= cur then
                pcall(function()
                    obj.Text = nt
                    obj.Font = Enum.Font.SourceSansBold
                end)
            end
        end

        pcall(function()
            obj:GetPropertyChangedSignal("Text"):Connect(applyText)
        end)
        if class == "TextBox" then
            pcall(function()
                obj:GetPropertyChangedSignal("PlaceholderText"):Connect(function()
                    local cur = obj.PlaceholderText
                    local np = tr(cur)
                    if np ~= cur then obj.PlaceholderText = np end
                end)
            end)
        end

        applyText()
    end

    local function scanContainer(container)
        if not container then return end
        pcall(function()
            for _, obj in ipairs(container:GetDescendants()) do
                if obj:IsA("TextLabel") or obj:IsA("TextButton")
                   or obj:IsA("TextBox") then
                    handleObject(obj, obj.ClassName)
                end
            end
        end)
    end

    task.spawn(function()
        print("[QO] 汉化扫描器已启动（每 0.5 秒扫描一次）")
        while true do
            scanContainer(LocalPlayer:FindFirstChild("PlayerGui"))
            pcall(scanContainer, game:GetService("CoreGui"))
            task.wait(0.5)
        end
    end)
end


